"""Write the routed board as a KiCad 8 .kicad_pcb (text S-expression)."""
import math
import uuid

from design import BOARD_W, BOARD_H, VIA_D, VIA_DRILL, CLEARANCE

OX, OY = 100.0, 60.0          # board origin on the KiCad sheet (A4)


def K(x, y):
    return OX + x, OY + (BOARD_H - y)


def u():
    return str(uuid.uuid4())


def f(v):
    return f"{v:.4f}".rstrip("0").rstrip(".") if abs(v) > 1e-9 else "0"


LAYERS = """  (layers
    (0 "F.Cu" signal)
    (31 "B.Cu" signal)
    (32 "B.Adhes" user "B.Adhesive")
    (33 "F.Adhes" user "F.Adhesive")
    (34 "B.Paste" user)
    (35 "F.Paste" user)
    (36 "B.SilkS" user "B.Silkscreen")
    (37 "F.SilkS" user "F.Silkscreen")
    (38 "B.Mask" user)
    (39 "F.Mask" user)
    (40 "Dwgs.User" user "User.Drawings")
    (41 "Cmts.User" user "User.Comments")
    (42 "Eco1.User" user "User.Eco1")
    (43 "Eco2.User" user "User.Eco2")
    (44 "Edge.Cuts" user)
    (45 "Margin" user)
    (46 "B.CrtYd" user "B.Courtyard")
    (47 "F.CrtYd" user "F.Courtyard")
    (48 "B.Fab" user)
    (49 "F.Fab" user)
    (50 "User.1" user)
    (51 "User.2" user)
  )"""


def effects(size=1.0, th=0.15):
    return f"(effects (font (size {size} {size}) (thickness {th})))"


def footprint(pt, netid, labels=True):
    ox, oy = K(pt.x, pt.y)
    lines = [f'  (footprint "PARKFNB:{pt.fp}" (layer "F.Cu") (uuid "{u()}") (at {f(ox)} {f(oy)})']
    cx, cy = (pt.bbox[0] + pt.bbox[2]) / 2, pt.bbox[3] + 1.2
    rx, ry = K(cx, cy)
    lines.append(f'    (property "Reference" "{pt.ref}" (at {f(rx - ox)} {f(ry - oy)}) (layer "F.SilkS") (uuid "{u()}") {effects(0.8, 0.12)})')
    lines.append(f'    (property "Value" "{pt.value}" (at 0 0) (layer "F.Fab") (hide yes) (uuid "{u()}") {effects(0.8, 0.12)})')
    lines.append(f'    (property "Footprint" "{pt.fp}" (at 0 0) (layer "F.Fab") (hide yes) (uuid "{u()}") {effects(0.8, 0.12)})')
    lines.append(f'    (property "Datasheet" "" (at 0 0) (layer "F.Fab") (hide yes) (uuid "{u()}") {effects(0.8, 0.12)})')
    lines.append(f'    (property "Description" "{pt.note}" (at 0 0) (layer "F.Fab") (hide yes) (uuid "{u()}") {effects(0.8, 0.12)})')
    lines.append("    (attr through_hole)" if pt.fp != "MOUNT" else "    (attr exclude_from_pos_files exclude_from_bom)")
    for it in pt.silk:
        if it[0] == "line":
            pts = it[1] + ([it[1][0]] if it[2] else [])
            for a, b in zip(pts[:-1], pts[1:]):
                ax, ay = K(*a)
                bx, by = K(*b)
                lines.append(f'    (fp_line (start {f(ax - ox)} {f(ay - oy)}) (end {f(bx - ox)} {f(by - oy)}) '
                             f'(stroke (width 0.15) (type solid)) (layer "F.SilkS") (uuid "{u()}"))')
        else:
            ccx, ccy = K(it[1], it[2])
            lines.append(f'    (fp_circle (center {f(ccx - ox)} {f(ccy - oy)}) (end {f(ccx - ox + it[3])} {f(ccy - oy)}) '
                         f'(stroke (width 0.15) (type solid)) (fill none) (layer "F.SilkS") (uuid "{u()}"))')
    if pt.fp == "MOUNT":
        lines.append(f'    (pad "" np_thru_hole circle (at 0 0) (size 3.2 3.2) (drill 3.2) (layers "*.Cu" "*.Mask") (uuid "{u()}"))')
    for pd in pt.pads:
        px, py = K(pd.x, pd.y)
        shape = "rect" if pd.shape == "r" else "circle"
        net = f'(net {netid[pd.net]} "{pd.net}")' if pd.net else ""
        lines.append(f'    (pad "{pd.num}" thru_hole {shape} (at {f(px - ox)} {f(py - oy)}) (size {f(pd.size)} {f(pd.size)}) '
                     f'(drill {f(pd.drill)}) (layers "*.Cu" "*.Mask") (remove_unused_layers no) {net} (uuid "{u()}"))')
    lines.append("  )")
    return "\n".join(lines)


def poly(points):
    return "(pts " + " ".join(f"(xy {f(x)} {f(y)})" for x, y in points) + ")"


def circle_pts(x, y, r, n=16):
    return [K(x + r * math.cos(2 * math.pi * k / n), y + r * math.sin(2 * math.pi * k / n)) for k in range(n)]


def write_kicad(path, parts, router, antenna, labels, nets):
    netid = {n: i + 1 for i, n in enumerate(sorted(nets))}
    out = ['(kicad_pcb', '  (version 20240108)', '  (generator "parkfnb_pcb_py")', '  (generator_version "1.0")',
           '  (general (thickness 1.6) (legacy_teardrops no))', '  (paper "A4")',
           '  (title_block (title "PARKFNB V2 controller PCB") (date "2026-10-26") (rev "A") '
           '(comment 1 "100 x 80 mm, 2 layers, through-hole") (comment 2 "Generated by generate_pcb.py - press B to fill zones"))',
           LAYERS,
           '  (setup (pad_to_mask_clearance 0) (allow_soldermask_bridges_in_footprints no)'
           ' (pcbplotparams (layerselection 0x00010fc_ffffffff) (plot_on_all_layers_selection 0x0000000_00000000)'
           ' (disableapertmacros no) (usegerberextensions no) (usegerberattributes yes) (usegerberadvancedattributes yes)'
           ' (creategerberjobfile yes) (dashed_line_dash_ratio 12.0) (dashed_line_gap_ratio 3.0) (svgprecision 4)'
           ' (plotframeref no) (viasonmask no) (mode 1) (useauxorigin no) (hpglpennumber 1) (hpglpenspeed 20) (hpglpendiameter 15.0)'
           ' (pdf_front_fp_property_popups yes) (pdf_back_fp_property_popups yes) (dxfpolygonmode yes) (dxfimperialunits yes)'
           ' (dxfusepcbnewfont yes) (psnegative no) (psa4output no) (plotreference yes) (plotvalue yes) (plotfptext yes)'
           ' (plotinvisibletext no) (sketchpadsonfab no) (subtractmaskfromsilk no) (outputformat 1) (mirror no)'
           ' (drillshape 1) (scaleselection 1) (outputdirectory "gerbers/")))',
           '  (net 0 "")']
    for n, i in sorted(netid.items(), key=lambda kv: kv[1]):
        out.append(f'  (net {i} "{n}")')
    for pt in parts:
        out.append(footprint(pt, netid))
    # board outline
    corners = [K(0, 0), K(BOARD_W, 0), K(BOARD_W, BOARD_H), K(0, BOARD_H)]
    for a, b in zip(corners, corners[1:] + corners[:1]):
        out.append(f'  (gr_line (start {f(a[0])} {f(a[1])}) (end {f(b[0])} {f(b[1])}) (stroke (width 0.1) (type default)) '
                   f'(layer "Edge.Cuts") (uuid "{u()}"))')
    # silkscreen labels
    for (txt, x, y, rot, size) in labels:
        px, py = K(x, y)
        out.append(f'  (gr_text "{txt}" (at {f(px)} {f(py)} {int(rot)}) (layer "F.SilkS") (uuid "{u()}") '
                   f'(effects (font (size {size} {size}) (thickness 0.12)) (justify left)))')
    # tracks and vias
    for (net, lay, x0, y0, x1, y1, w) in router.tracks:
        a, b = K(x0, y0), K(x1, y1)
        out.append(f'  (segment (start {f(a[0])} {f(a[1])}) (end {f(b[0])} {f(b[1])}) (width {f(w)}) '
                   f'(layer "{lay}.Cu") (net {netid[net]}) (uuid "{u()}"))')
    for (net, x, y) in router.vias:
        a = K(x, y)
        out.append(f'  (via (at {f(a[0])} {f(a[1])}) (size {f(VIA_D)}) (drill {f(VIA_DRILL)}) (layers "F.Cu" "B.Cu") '
                   f'(net {netid[net]}) (uuid "{u()}"))')
    # GND plane on the bottom layer + keep-outs
    e = 0.4
    out.append(f'  (zone (net {netid["GND"]}) (net_name "GND") (layer "B.Cu") (uuid "{u()}") (name "GND_plane") (hatch edge 0.5) '
               f'(connect_pads (clearance {f(CLEARANCE)})) (min_thickness 0.25) (filled_areas_thickness no) '
               f'(fill yes (thermal_gap 0.4) (thermal_bridge_width 0.5)) '
               f'(polygon {poly([K(e, e), K(BOARD_W - e, e), K(BOARD_W - e, BOARD_H - e), K(e, BOARD_H - e)])}))')
    x0, y0, x1, y1 = antenna
    out.append(f'  (zone (net 0) (net_name "") (layers "F&B.Cu") (uuid "{u()}") (name "ESP32_antenna_keepout") (hatch edge 0.5) '
               f'(connect_pads (clearance 0)) (min_thickness 0.25) (filled_areas_thickness no) '
               f'(keepout (tracks not_allowed) (vias not_allowed) (pads allowed) (copperpour not_allowed) (footprints allowed)) '
               f'(fill (thermal_gap 0.5) (thermal_bridge_width 0.5)) '
               f'(polygon {poly([K(x0, y0), K(x1, y0), K(x1, y1 + 0.5), K(x0, y1 + 0.5)])}))')
    for pt in parts:
        if pt.fp == "MOUNT":
            out.append(f'  (zone (net 0) (net_name "") (layers "F&B.Cu") (uuid "{u()}") (name "{pt.ref}_keepout") (hatch edge 0.5) '
                       f'(connect_pads (clearance 0)) (min_thickness 0.25) (filled_areas_thickness no) '
                       f'(keepout (tracks not_allowed) (vias not_allowed) (pads allowed) (copperpour not_allowed) (footprints allowed)) '
                       f'(fill (thermal_gap 0.5) (thermal_bridge_width 0.5)) '
                       f'(polygon {poly(circle_pts(pt.x, pt.y, 3.25))}))')
    out.append(")")
    with open(path, "w", encoding="utf8") as fh:
        fh.write("\n".join(out) + "\n")
